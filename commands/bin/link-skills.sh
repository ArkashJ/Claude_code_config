#!/bin/sh
# One real copy per skill; the other agent links to it. Run by claude-sync (push + pull).
#
# 2026-09-22: a sync had turned every shared skill into TWO real copies (~/.claude/skills and
# ~/.agents/skills). Edits to `qa` landed in ~/.claude while Codex kept reading a copy three hours
# stale; `document-consolidation` in the repo had lost its SKILL.md; the Codex variants of
# start/wrap/mission reappeared in Claude and shadowed the /start /wrap /mission commands.
#
#   agents-owned : third-party installs in ~/.agents/.skill-lock.json, and any ~/.agents skill that is
#                  its own git repo  ->  ~/.claude/skills/<n> is a symlink to ~/.agents/skills/<n>
#   codex-only   : start wrap checkpoint mission (generated by commands/.codex/sync.sh)
#                  ->  not in ~/.claude/skills at all (Claude uses ~/.claude/commands/*.md)
#   claude-owned : every other real dir in ~/.claude/skills (tracked in git)
#                  ->  ~/.agents/skills/<n> is a symlink to ~/.claude/skills/<n>  (Codex reads ~/.agents)
# A real copy that would be replaced is moved to ~/.agents/.replaced/<n>-<stamp>, never deleted.
set -eu
C="$HOME/.claude/skills"; A="$HOME/.agents/skills"; R="$HOME/.agents/.replaced"; stamp=$(date +%Y%m%d-%H%M%S)
[ -d "$A" ] || { echo "link-skills: no $A, skipped"; exit 0; }
CODEX_ONLY=$(ls "$HOME/.claude/commands/.codex/"*.prompt 2>/dev/null | sed 's#.*/##;s#\.prompt$##' | tr '\n' ' ')  # generated for Codex by .codex/sync.sh
agents_owned=$(python3 -c 'import json,os;p=os.path.expanduser("~/.agents/.skill-lock.json");print(" ".join(json.load(open(p)).get("skills",{})) if os.path.exists(p) else "")')
for d in "$A"/*/; do [ -d "$d/.git" ] && agents_owned="$agents_owned $(basename "$d")"; done
has() { case " $1 " in *" $2 "*) return 0;; esac; return 1; }
backup() { mkdir -p "$R"; mv "$1" "$R/$(basename "$1")-$stamp"; echo "link-skills: backed up $1 -> $R/$(basename "$1")-$stamp"; }
linked=0

for n in $CODEX_ONLY; do  # Claude uses the commands; the skill copies only shadow them
  [ -e "$C/$n" ] || [ -L "$C/$n" ] || continue
  if [ -L "$C/$n" ]; then rm "$C/$n"; else backup "$C/$n"; fi
  echo "link-skills: removed codex-only $n from ~/.claude/skills"
done

for n in $agents_owned; do
  [ -d "$A/$n" ] && [ ! -L "$A/$n" ] || continue
  [ -L "$C/$n" ] && [ "$(readlink "$C/$n")" = "../../.agents/skills/$n" ] && continue
  [ -e "$C/$n" ] && backup "$C/$n"
  ln -s "../../.agents/skills/$n" "$C/$n"; linked=$((linked + 1))
done

for d in "$C"/*/; do
  n=$(basename "$d")
  [ "$n" = synced ] || [ -L "$C/$n" ] || has "$agents_owned" "$n" || has "$CODEX_ONLY" "$n" || {
    [ -L "$A/$n" ] && [ "$(readlink "$A/$n")" = "$C/$n" ] && continue
    [ -e "$A/$n" ] || [ -L "$A/$n" ] && backup "$A/$n"
    ln -s "$C/$n" "$A/$n"; linked=$((linked + 1))
  }
done
dangling=$(find "$A" "$C" -maxdepth 1 -type l ! -exec test -e {} \; -print)
if [ -n "$dangling" ]; then
  echo "link-skills: DANGLING links (an agent would load nothing):" >&2; echo "$dangling" >&2
  echo "link-skills: fix: run commands/.codex/sync.sh for codex-only names, or restore from ~/.agents/.replaced/" >&2
  exit 1
fi
echo "link-skills: $linked link(s) created; agents-owned:$(echo "$agents_owned" | wc -w | tr -d ' ') codex-only:$(echo "$CODEX_ONLY" | wc -w | tr -d ' ')"
